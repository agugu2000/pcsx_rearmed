#!/usr/bin/env python3
"""
Generate the embedded cheat database C source from cheat_bilingual.json.

Usage:
  python3 tools/gen_cheat_db.py <cheat_json> <output_c_file>
  python3 tools/gen_cheat_db.py --check [--strict] <cheat_json> <reference_c_file>

<cheat_json> is the bilingual pack, the single source of truth:

  {
    "SLUS01234.CHT": [
      {"en_string": "Infinite health", "cn_string": "生命无限",
       "code": "800856D2 000C\\n80136198 099F"},
      ...
    ],
    ...
  }

Each key is one disc id, each list item one cheat in the order the game will
show them. A multi-disc release repeats the same body under each of its ids,
so every disc resolves on its own.

The output is a C file with:
  - A sorted index array mapping game_id -> offset into data blob
  - A raw data blob holding both names and the codes

Blob layout, little endian, one game after another:

  u16 cn_len  [cn bytes]
  u16 en_len  [en bytes]
  u16 n_codes [u32 addr, u16 value] * n_codes
  ...
  u16 0x0000                      end of game

The generator refuses to write anything if a cheat cannot be decoded back
into an address and a value: a line that is not "8 hex digits, space,
4 hex digits", a name that is empty or carries a bracket or a newline
(SaveCheats() writes names back as "[name]", so those would corrupt a saved
.cht), a duplicate game id, a count that does not fit a u16 field. Those are
faults in the pack itself, and they would corrupt the database.

Code types the emulator has no handler for are *not* treated as faults:
libpcsxcore/cheat.c gives up on such a cheat at runtime by itself, and the
pack keeps what the source said. They are reported as notes so a dead cheat
can still be spotted in the build log.

--check compares the code lists built from <cheat_json> against any
previously generated file and ignores the names, so a pass that only
rewrites the names can be proven not to have touched an address or a value.
"""
import json
import os
import re
import sys

FORMAT_VERSION = 1

HEADER = """/* Auto-generated cheat database - do not edit by hand */
/* Generated by tools/gen_cheat_db.py from deps/cheat_bilingual.json */
/* This file is included from libretro_cheats.c */

#include <stdint.h>
#include <stddef.h>
#include <string.h>

/* Blob layout this file was written in; libretro_cheats.c refuses to
   compile against anything else. */
#define CHEAT_DB_FORMAT %d

""" % FORMAT_VERSION

CODE_RE = re.compile(r'^([0-9A-F]{8}) ([0-9A-F]{4})$')
BLOB_START = 'static const uint8_t cheat_db_blob[] = {'

# CdromId as the PSX CD layer reports it: four letters, five digits.
# Anything else can never match a real disc, so it is a fault in the pack.
GAME_ID_RE = re.compile(r'^[A-Za-z]{4}[0-9]{5}$')

# Types libpcsxcore/cheat.c has a case for. Anything else hits its default:
# branch, which prints once and turns the whole cheat off - that is the
# engine's own decision, not a reason to stop the build.
SUPPORTED_TYPES = {
    0x10, 0x11, 0x1F, 0x20, 0x21, 0x30, 0x50, 0x80, 0xC2,
    0xD0, 0xD1, 0xD2, 0xD3, 0xD4,
    0xE0, 0xE1, 0xE2, 0xE3,
}

# AddCheat() ignores a line below this without telling anyone.
LOW_ADDR = 0x10000000

MAX_U16 = 0xFFFF
WARN_DETAILS = 10


class PackError(Exception):
    pass


# json's object hook runs before the object's parent exists, so a raise here
# could only name the key, not the game it is in. Stash the finding under a
# key that cannot collide (control characters are rejected everywhere else)
# and let the caller walk the finished tree to say where it happened.
DUP_KEY = '\x00duplicate'


def _pairs(pairs):
    """Object hook that remembers duplicate keys: json.load would keep the
    last one and silently drop a cheat."""
    seen = set()
    dup = []
    for key, _ in pairs:
        if key in seen:
            dup.append(key)
        seen.add(key)
    obj = dict(pairs)
    if dup:
        obj[DUP_KEY] = dup
    return obj


def find_duplicates(pack):
    """Return one message per duplicate key found, with the game it is in."""
    out = []
    if not isinstance(pack, dict):
        return out

    for key in pack.get(DUP_KEY, []):
        out.append('key "%s" appears more than once at the top level' % key)

    for filename, entries in pack.items():
        if filename == DUP_KEY:
            continue
        if isinstance(entries, dict):
            for key in entries.get(DUP_KEY, []):
                out.append('%s: key "%s" appears more than once'
                           % (filename, key))
            continue
        if not isinstance(entries, list):
            continue
        for idx, entry in enumerate(entries, 1):
            if not isinstance(entry, dict):
                continue
            for key in entry.get(DUP_KEY, []):
                out.append('%s cheat %d: key "%s" appears more than once'
                           % (filename, idx, key))
    return out


def strip_to_cdrom_id(filename):
    """SLUS_012.34.CHT -> SLUS01234"""
    name = filename
    if name.upper().endswith('.CHT'):
        name = name[:-4]
    return ''.join(c.upper() for c in name
                   if ('0' <= c <= '9') or ('A' <= c <= 'Z') or
                      ('a' <= c <= 'z'))


def check_name(value, what, where):
    if not isinstance(value, str):
        raise PackError('%s: %s is not a string' % (where, what))
    name = value.strip()
    if not name:
        raise PackError('%s: %s is empty' % (where, what))
    # SaveCheats() writes "[name]" back out, so a bracket or a newline here
    # would produce a .cht that no longer parses.
    for bad in ('[', ']', '\n', '\r', '\t'):
        if bad in value:
            raise PackError('%s: %s contains %r' % (where, what, bad))
    if any(ord(c) < 0x20 or ord(c) == 0x7F for c in value):
        raise PackError('%s: %s contains a control character' % (where, what))
    raw = name.encode('utf-8')
    if len(raw) > MAX_U16:
        raise PackError('%s: %s is %d bytes, limit is %d'
                        % (where, what, len(raw), MAX_U16))
    return name


def parse_codes(value, where, warnings):
    if not isinstance(value, str):
        raise PackError('%s: code is not a string' % where)

    lines = value.split('\n')
    if not lines or not lines[0]:
        raise PackError('%s: code is empty' % where)

    codes = []
    for i, line in enumerate(lines, 1):
        m = CODE_RE.match(line)
        if m is None:
            raise PackError('%s: line %d is %r, expected "XXXXXXXX VVVV" '
                            '(8 hex digits, space, 4 hex digits)'
                            % (where, i, line))
        addr = int(m.group(1), 16)
        val = int(m.group(2), 16)
        if addr < LOW_ADDR:
            warnings['low-addr'].append('%s line %d: %s' % (where, i, line))
        kind = addr >> 24
        if kind not in SUPPORTED_TYPES:
            warnings['unsupported-type'].append(
                '%s line %d: type 0x%02X' % (where, i, kind))
        codes.append((addr, val))

    if len(codes) > MAX_U16:
        raise PackError('%s: %d code lines, limit is %d'
                        % (where, len(codes), MAX_U16))
    return codes


def load_pack(path, warnings):
    """Return {game_id: [(cn, en, [(addr, value), ...]), ...]}."""
    try:
        with open(path, 'r', encoding='utf-8') as f:
            text = f.read()
    except OSError as e:
        raise PackError('cannot read %s: %s' % (path, e))
    except UnicodeDecodeError as e:
        raise PackError('%s is not valid UTF-8 at byte %d' % (path, e.start))

    try:
        pack = json.loads(text, object_pairs_hook=_pairs)
    except ValueError as e:
        raise PackError('%s is not valid JSON: %s' % (path, e))

    dup = find_duplicates(pack)
    if dup:
        more = '' if len(dup) == 1 else ' (and %d more)' % (len(dup) - 1)
        raise PackError('%s: %s%s' % (path, dup[0], more))

    if not isinstance(pack, dict):
        raise PackError('%s: top level is not an object' % path)
    if not pack:
        raise PackError('%s: no games' % path)

    games = {}
    seen_ids = {}
    for filename, entries in pack.items():
        if not filename.upper().endswith('.CHT'):
            raise PackError('"%s" is not a .CHT file name' % filename)
        game_id = strip_to_cdrom_id(filename)
        if not GAME_ID_RE.match(game_id):
            raise PackError('"%s" does not yield a CdromId (got "%s")'
                            % (filename, game_id))
        if game_id in seen_ids:
            raise PackError('"%s" and "%s" both map to %s'
                            % (seen_ids[game_id], filename, game_id))
        seen_ids[game_id] = filename

        if not isinstance(entries, list):
            raise PackError('%s: not a list of cheats' % filename)
        # An empty list would quietly vanish from the database - the game
        # would look like it never had cheats. A pack entry with nothing in
        # it is a mistake, so say so instead of dropping it.
        if not entries:
            raise PackError('%s: no cheats' % filename)

        rows = games.setdefault(game_id, [])
        for idx, entry in enumerate(entries, 1):
            where = '%s cheat %d' % (filename, idx)
            if not isinstance(entry, dict):
                raise PackError('%s: not an object' % where)
            missing = {'en_string', 'cn_string', 'code'} - set(entry)
            extra = set(entry) - {'en_string', 'cn_string', 'code'}
            if missing:
                raise PackError('%s: missing %s' % (where, sorted(missing)))
            if extra:
                raise PackError('%s: unexpected field %s' % (where, sorted(extra)))
            cn = check_name(entry['cn_string'], 'cn_string', where)
            en = check_name(entry['en_string'], 'en_string', where)
            codes = parse_codes(entry['code'], where, warnings)
            rows.append((cn, en, codes))

        if len(rows) > MAX_U16:
            raise PackError('%s: %d cheats, limit is %d'
                            % (filename, len(rows), MAX_U16))

    return games


def build_blob(games):
    """Return (blob, [(game_id, offset, n_cheats, n_codes), ...]).

    Names are encoded as UTF-8. The per-game counts travel with the index so
    the C side allocates exactly what the data needs and has no fixed caps to
    keep in sync when the source pack changes.

    Every game gets its own copy even when a multi-disc release repeats the
    same body: libretro_cheats.c works out where a game's data ends from the
    *next* index entry's offset, so offsets must stay strictly increasing.
    """
    ids = sorted(games)
    chunks = []
    index = []
    offset = 0

    for game_id in ids:
        if len(game_id) > 11:
            raise PackError('%s: id longer than 11 chars' % game_id)

        body = bytearray()
        n_cheats = n_codes = 0
        for cn, en, codes in games[game_id]:
            for name in (cn, en):
                raw = name.encode('utf-8')
                body += len(raw).to_bytes(2, 'little')
                body += raw
            body += len(codes).to_bytes(2, 'little')
            for addr, value in codes:
                body += addr.to_bytes(4, 'little')
                body += value.to_bytes(2, 'little')
            n_cheats += 1
            n_codes += len(codes)

        if n_cheats == 0:
            continue

        body += b'\x00\x00'
        index.append((game_id, offset, n_cheats, n_codes))
        chunks.append(bytes(body))
        offset += len(body)

    # blob_offset is a uint32_t on the C side and is written as a plain
    # decimal literal, so keep it inside int range: a pack that big would
    # also mean the index no longer addresses it correctly.
    if offset > 0x7FFFFFFF:
        raise PackError('blob would be %d bytes, beyond what a 32-bit offset '
                        'can address' % offset)

    return b''.join(chunks), index


def render(blob, index):
    out = [HEADER]
    out.append('static const uint8_t cheat_db_blob[] = {\n')
    for i in range(0, len(blob), 16):
        out.append('  ' + ', '.join('0x%02X' % b for b in blob[i:i + 16]) + ',\n')
    out.append('};\n\n')
    out.append('#define CHEAT_DB_GAME_COUNT %d\n\n' % len(index))
    out.append('typedef struct {\n')
    out.append('  char game_id[12];\n')
    out.append('  uint32_t blob_offset;\n')
    out.append('  uint32_t n_cheats;\n')
    out.append('  uint32_t n_codes;\n')
    out.append('} cheat_db_index_t;\n\n')
    out.append('static const cheat_db_index_t cheat_db_index[] = {\n')
    for game_id, offset, n_cheats, n_codes in index:
        padded = game_id.ljust(12, '\0')
        chars = ', '.join("'%s'" % (c if c != '\0' else '\\0') for c in padded)
        out.append('  { { %s }, %d, %d, %d },\n'
                   % (chars, offset, n_cheats, n_codes))
    out.append('};\n\n')
    out.append("""static const cheat_db_index_t *cheat_db_find(const char *game_id)
{
  if (!game_id) return NULL;

  int lo = 0, hi = CHEAT_DB_GAME_COUNT - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    int cmp = strcmp(game_id, cheat_db_index[mid].game_id);
    if (cmp == 0)
      return &cheat_db_index[mid];
    else if (cmp < 0)
      hi = mid - 1;
    else
      lo = mid + 1;
  }
  return NULL;
}
""")
    return ''.join(out)


def write_if_changed(path, text):
    data = text.encode('utf-8')
    try:
        if open(path, 'rb').read() == data:
            return False
    except OSError:
        pass
    tmp = '%s.tmp.%d' % (path, os.getpid())
    with open(tmp, 'wb') as f:
        f.write(data)
    os.replace(tmp, path)
    return True


def read_reference(path):
    """Pull (name, codes) out of an existing generated file."""
    try:
        text = open(path, 'r', encoding='utf-8', errors='replace').read()
    except OSError as e:
        print('cannot read reference: %s' % e, file=sys.stderr)
        sys.exit(1)

    start = text.find(BLOB_START)
    if start < 0:
        print('no blob in reference file', file=sys.stderr)
        sys.exit(1)
    m = re.search(r'#define CHEAT_DB_FORMAT (\d+)', text)
    if m is None or int(m.group(1)) != FORMAT_VERSION:
        print('reference file is format %s, this generator writes %d - '
              'regenerate the baseline from the same pack'
              % (m.group(1) if m else 'unknown', FORMAT_VERSION), file=sys.stderr)
        sys.exit(1)
    end = text.find('};', start)
    blob = bytes(int(h, 16) for h in re.findall(r'0x([0-9A-Fa-f]{2})', text[start:end]))

    index = {}
    m = re.search(r'static const cheat_db_index_t cheat_db_index\[\] = \{(.*?)\n\};',
                  text, re.S)
    if m is None:
        print('no cheat index in reference file', file=sys.stderr)
        sys.exit(1)
    for entry in re.finditer(r"\{\s*\{([^}]*)\}\s*,\s*(\d+)[^}]*\}", m.group(1)):
        chars = ''.join(re.findall(r"'([^']*)'", entry.group(1)))
        index[chars.replace('\\0', '').replace('\0', '')] = int(entry.group(2))

    games = {}
    for game_id, offset in sorted(index.items(), key=lambda kv: kv[1]):
        if offset >= len(blob):
            print('reference: %s starts at %d, past the end of the blob (%d) '
                  '- the file is truncated' % (game_id, offset, len(blob)),
                  file=sys.stderr)
            sys.exit(1)
        pos = offset
        items = []
        while True:
            if pos + 2 > len(blob):
                print('reference: %s is truncated at offset %d'
                      % (game_id, pos), file=sys.stderr)
                sys.exit(1)
            cn_len = blob[pos] | (blob[pos + 1] << 8)
            pos += 2
            if cn_len == 0:
                break
            if pos + cn_len + 4 > len(blob):
                print('reference: %s name runs past the end at offset %d'
                      % (game_id, pos), file=sys.stderr)
                sys.exit(1)
            cn = blob[pos:pos + cn_len].decode('utf-8', 'replace')
            pos += cn_len
            en_len = blob[pos] | (blob[pos + 1] << 8)
            pos += 2
            if pos + en_len + 2 > len(blob):
                print('reference: %s second name runs past the end at offset %d'
                      % (game_id, pos), file=sys.stderr)
                sys.exit(1)
            pos += en_len
            count = blob[pos] | (blob[pos + 1] << 8)
            pos += 2
            if pos + count * 6 > len(blob):
                print('reference: %s has %d codes but only %d bytes left'
                      % (game_id, count, len(blob) - pos), file=sys.stderr)
                sys.exit(1)
            codes = []
            for _ in range(count):
                addr = int.from_bytes(blob[pos:pos + 4], 'little')
                value = int.from_bytes(blob[pos + 4:pos + 6], 'little')
                pos += 6
                codes.append((addr, value))
            items.append((cn, codes))
        games[game_id] = items

    return games


def report_warnings(warnings):
    items = warnings['unsupported-type']
    if items:
        print('note: %d code lines use a type libpcsxcore/cheat.c has no case '
              'for; the engine turns such a cheat off by itself at runtime'
              % len(items), file=sys.stderr)
        for line in items[:WARN_DETAILS]:
            print('  %s' % line, file=sys.stderr)
        if len(items) > WARN_DETAILS:
            print('  ... %d more' % (len(items) - WARN_DETAILS), file=sys.stderr)

    items = warnings['low-addr']
    if items:
        print('note: %d code lines sit below 0x10000000 and are dropped by '
              'AddCheat()' % len(items), file=sys.stderr)
        for line in items[:WARN_DETAILS]:
            print('  %s' % line, file=sys.stderr)


def check(source, reference, strict_coverage=False):
    """Compare the code lists of source against an already generated file.

    A game that is gone from source (or a new one) is a coverage change, not a
    corruption: dropping a broken .CHT is a legitimate edit. Those are reported
    but do not fail the run unless strict_coverage is set. What always fails is
    a game that is still there with different codes, or with a different number
    of cheats - that means the edit damaged existing data.
    """
    warnings = {'unsupported-type': [], 'low-addr': []}
    try:
        games = load_pack(source, warnings)
    except PackError as e:
        print('problem: %s' % e, file=sys.stderr)
        sys.exit(1)
    ref = read_reference(reference)

    diffs = 0
    missing = sorted(set(ref) - set(games))
    added = sorted(set(games) - set(ref))

    for game_id in sorted(set(games) & set(ref)):
        new = games[game_id]
        old = ref[game_id]
        if len(new) != len(old):
            print('%s: cheat count %d -> %d' % (game_id, len(old), len(new)))
            diffs += 1
            continue
        for i, ((cn, en, new_codes), (old_name, old_codes)) in enumerate(zip(new, old)):
            if new_codes != old_codes:
                print('%s[%d] "%s": codes differ' % (game_id, i, old_name))
                diffs += 1

    if diffs:
        print('FAILED: %d mismatches' % diffs, file=sys.stderr)
        sys.exit(1)

    for game_id in missing:
        print('note: %s dropped (%d cheats in reference)' % (game_id, len(ref[game_id])))
    for game_id in added:
        print('note: %s is new (%d cheats)' % (game_id, len(games[game_id])))

    if missing or added:
        print('coverage: %d dropped, %d new (add --strict to fail on this)'
              % (len(missing), len(added)))
        if strict_coverage:
            print('FAILED: coverage changed', file=sys.stderr)
            sys.exit(1)

    total = sum(len(v) for v in games.values())
    print('OK: %d games, %d cheats, codes identical to reference' % (len(games), total))


def main():
    if len(sys.argv) > 2 and sys.argv[1] == '--check':
        args = sys.argv[2:]
        strict = False
        if args and args[0] == '--strict':
            strict = True
            args = args[1:]
        if len(args) != 2:
            print('usage: %s --check [--strict] <cheat_json> <reference_c_file>'
                  % sys.argv[0], file=sys.stderr)
            sys.exit(1)
        check(args[0], args[1], strict)
        return

    if len(sys.argv) != 3:
        print('Usage: %s <cheat_json> <output_c_file>' % sys.argv[0], file=sys.stderr)
        print('       %s --check [--strict] <cheat_json> <reference_c_file>'
              % sys.argv[0], file=sys.stderr)
        sys.exit(1)

    source, output_path = sys.argv[1], sys.argv[2]
    if not os.path.isfile(source):
        print('not a file: %s' % source, file=sys.stderr)
        sys.exit(1)

    warnings = {'unsupported-type': [], 'low-addr': []}
    try:
        games = load_pack(source, warnings)
        blob, index = build_blob(games)
    except PackError as e:
        print('problem: %s' % e, file=sys.stderr)
        print('refusing to write: the pack has a fault the database cannot '
              'represent', file=sys.stderr)
        sys.exit(1)

    # An empty database still compiles (a zero-length array is a GCC
    # extension) and would silently ship a core with no cheats at all, so
    # treat it as a hard error instead.
    if not index or not blob:
        print('refusing to write: no cheats found in %s' % source, file=sys.stderr)
        sys.exit(1)

    report_warnings(warnings)

    text = render(blob, index)
    changed = write_if_changed(output_path, text)

    cheats = sum(len(v) for v in games.values())
    codes = sum(len(c) for v in games.values() for _, _, c in v)
    print('%s: %d cheats, %d codes, %d games, %d bytes%s'
          % (output_path, cheats, codes, len(index), len(blob),
             '' if changed else ' (unchanged)'))


if __name__ == '__main__':
    main()
